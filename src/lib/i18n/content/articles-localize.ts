function buildGuideParagraphsMr(topic: string, category: string): string[] {
  return buildGuideParagraphsHi(topic, category).map((p) =>
    p
      .replace(/माता-पिता/g, "पालक")
      .replace(/करती हैं/g, "करतात")
      .replace(/प्रदान करती हैं/g, "प्रदान करतात")
      .replace(/में/g, "मध्ये")
      .replace(/के लिए/g, "साठी")
      .replace(/कैसे/g, "कसे")
      .replace(/क्यों/g, "का")
      .replace(/सिफ़ारिश/g, "शिफारस")
      .replace(/स्वागत करती हैं/g, "स्वागत करतात"),
  );
}

const categoryHi: Record<string, string> = {
  "Parent Guidance": "माता-पिता मार्गदर्शन",
  "Child Development": "बाल विकास",
  ADHD: "एडीएचडी",
  Handwriting: "हस्तलेखन",
  "Aquatic Therapy": "जल चिकित्सा",
  Autism: "ऑटिज़म",
  "Sensory Processing": "संवेदी प्रसंस्करण",
  "School Readiness": "स्कूल तैयारी",
  "Emotional Regulation": "भावनात्मक नियमन",
  "Fine Motor Development": "फाइन मोटर विकास",
  "Learning Difficulties": "सीखने की कठिनाइयाँ",
  "Executive Functioning": "कार्यकारी कार्य",
  "Parenting Support": "माता-पिता सहायता",
};

const categoryMr: Record<string, string> = Object.fromEntries(
  Object.entries(categoryHi).map(([k, v]) => [k, v.replace("माता-पिता", "पालक")]),
);

function localizeGuideArticle(article: Article, locale: Locale): Article {
  const topic = article.slug.replace(/^guide-/, "").replace(/-/g, " ");
  const paragraphs =
    locale === "hi"
      ? buildGuideParagraphsHi(topic, article.category)
      : buildGuideParagraphsMr(topic, article.category);
  const titleCase = topic.replace(/\b\w/g, (c) => c.toUpperCase());
  const catMap = locale === "hi" ? categoryHi : categoryMr;
  const cat = catMap[article.category] ?? article.category;
  const guideLabel = locale === "mr" ? "पालक मार्गदर्शक" : "माता-पिता गाइड";

  return {
    ...article,
    title: `${titleCase}: ${guideLabel}`,
    description:
      locale === "mr"
        ? `डॉ. शारुजा सराफ कडून ${topic} वर तज्ञ पालक मार्गदर्शक — कांदिवली पश्चिम, मुंबईतील बाल व्यावसायिक चिकित्सक.`
        : `डॉ. शारुजा सराफ से ${topic} पर विशेषज्ञ माता-पिता गाइड — कांदिवली पश्चिम, मुंबई में बाल व्यावसायिक चिकित्सक।`,
    excerpt:
      locale === "mr"
        ? `${topic} वर पुरावा-आधारित मार्गदर्शन मुंबई पालकांसाठी — काय पाहावे, थेरपी कशी मदत करते आणि सहाय्य कधी घ्यावे.`
        : `${topic} पर मुंबई माता-पिता के लिए साक्ष्य-सूचित मार्गदर्शन — क्या देखें, थेरेपी कैसे मदद करती है, और सहायता कब लें।`,
    category: cat,
    readTime: locale === "mr" ? "5 मिनिटे" : "5 मिनट",
    content: paragraphs,
  };
}

export function localizeArticle(article: Article, locale: Locale): Article {
  if (locale === "en") return article;

  if (article.slug.startsWith("guide-")) {
    return localizeGuideArticle(article, locale);
  }

  const map = locale === "hi" ? seedHi : seedMr;
  const override = map[article.slug];
  if (!override) return article;

  return { ...article, ...override };
}
